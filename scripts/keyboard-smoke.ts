import { chromium } from "playwright";
import assert from "node:assert/strict";

const browser = await chromium.launch({ headless: true });
const origin = process.env.ACHILIAS_TEST_URL || "http://127.0.0.1:3000";
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const clearFocus = () => page.evaluate(() => (document.activeElement as HTMLElement)?.blur());
  const activeIndex = (selector: string) => page.locator(selector).evaluateAll((elements) =>
    elements.findIndex((element) => element.contains(document.activeElement)));
  await page.goto(origin + "/courses?demo=1");
  const cards = page.locator(".course-card");
  await cards.first().waitFor();
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex(".course-card"), 0);
  await page.keyboard.press("l");
  assert.equal(await activeIndex(".course-card"), 1);
  await page.keyboard.press("h");
  assert.equal(await activeIndex(".course-card"), 0);
  await page.keyboard.press("j");
  const below = await activeIndex(".course-card");
  assert.ok(below > 1, "J moves to the next grid row");
  await page.keyboard.press("k");
  assert.equal(await activeIndex(".course-card"), 0);
  await page.keyboard.press("k");
  assert.equal(await activeIndex(".course-card"), 0, "Grid navigation stays within resources");
  await page.keyboard.press("Tab");
  assert.equal(await cards.first().evaluate((el) => el.contains(document.activeElement) && document.activeElement?.tagName === "BUTTON"), true);
  await page.keyboard.press("/");
  await page.getByRole("combobox").waitFor();
  await page.keyboard.type("hjkl/f?");
  assert.equal(await page.getByRole("combobox").inputValue(), "hjkl/f?");
  await page.keyboard.press("Escape");
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await page.keyboard.press("f");
  assert.equal(await page.getByText("Type a hint to activate", { exact: false }).count(), 0);

  await page.setViewportSize({ width: 390, height: 844 });
  await cards.first().locator(".resource-primary").focus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex(".course-card"), 1, "Mobile grid follows its single column");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin + "/browse/crs/101?demo=1");
  await page.getByRole("radio", { name: "List view" }).click();
  await page.locator(".resource-row").first().waitFor();
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex(".resource-row"), 0);
  await page.keyboard.press("j");
  assert.equal(await activeIndex(".resource-row"), 1);
  await page.keyboard.press("k");
  assert.equal(await activeIndex(".resource-row"), 0);

  await page.goto(origin + "/forums/402?demo=1");
  const topics = page.locator("[data-discussion-link]");
  await topics.first().waitFor();
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex("[data-discussion-link]"), 0);
  await page.keyboard.press("j");
  assert.equal(await activeIndex("[data-discussion-link]"), 1);
  await page.keyboard.press("k");
  assert.equal(await activeIndex("[data-discussion-link]"), 0);
  await page.keyboard.press("Enter");
  const posts = page.locator("article[data-post-kind]");
  await posts.first().waitFor();
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), 0);
  await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), 1);
  await page.keyboard.press("k");
  assert.equal(await activeIndex("article[data-post-kind]"), 0);
  await page.keyboard.press("h");
  assert.equal(await activeIndex("article[data-post-kind]"), 0, "Forum H does not jump to unrelated controls");
  for (let step = 0; step < await posts.count() + 2; step++) await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), await posts.count() - 1, "J stops at the final post");
  await page.getByRole("radio", { name: "Newest first", exact: true }).click();
  await page.waitForURL(/order=newest/);
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), 0, "Post navigation follows the displayed sort order");
  await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), 1);
  const input = page.getByRole("textbox", { name: "Search posts on this page" });
  const author = (await posts.first().getByRole("heading", { level: 2 }).innerText()).trim();
  await input.fill("jk");
  assert.equal(await input.inputValue(), "jk");
  await input.fill(author);
  await posts.first().waitFor();
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), 0, "Post navigation follows filtered results");
  await input.fill("");
  await clearFocus();
  await page.keyboard.press("?");
  await page.getByRole("dialog").waitFor();
  await page.getByRole("checkbox", { name: "Enable single-key shortcuts" }).uncheck();
  await page.keyboard.press("Escape");
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await clearFocus();
  await page.keyboard.press("j");
  assert.equal(await activeIndex("article[data-post-kind]"), -1);
  await page.reload();
  await posts.first().waitFor();
  await page.keyboard.press("/");
  assert.equal(await page.getByRole("dialog").count(), 0);
  await page.keyboard.press("Control+k");
  await page.getByRole("dialog").waitFor();
  console.log("Page-specific resource and forum shortcuts passed");
} finally {
  await browser.close();
}
